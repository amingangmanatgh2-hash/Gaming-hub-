def vis(s): return get_display(arabic_reshaper.reshape(s))
def width(d,s,f): return d.textbbox((0,0),vis(s),font=f)[2]
def wrap(d,s,f,maxw):
    out=[]; cur=''
    for word in s.split():
        t=(cur+' '+word).strip()
        if width(d,t,f)<=maxw: cur=t
        else:
            if cur: out.append(cur)
            cur=word
    if cur: out.append(cur)
    return out
